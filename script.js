// Browsers block fetch() on file:// pages, so .docx files also ship as base64 scripts in assets/docx/data.
async function readDocxBuffer(source, absoluteUrl) {
  try {
    const response = await fetch(absoluteUrl);
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return await response.arrayBuffer();
  } catch (error) {
    const parts = source.split("/");
    const key = `${parts[parts.length - 2]}-${parts[parts.length - 1].replace(/\.docx$/i, "")}`;
    await loadScript(`assets/docx/data/${key}.js`);
    const base64 = window.wordDocuments?.[key];
    if (!base64) throw error;
    return Uint8Array.from(atob(base64), (char) => char.charCodeAt(0)).buffer;
  }
}

// .docx renders locally; legacy .doc needs the Office web viewer, which requires a public URL.
async function openWordDocument(source, title) {
  if (!docxViewer) return;
  documentViewer.hidden = true;
  documentViewer.src = "about:blank";
  docxViewer.hidden = false;
  showWordMessage(translate("document.loading"));
  const absoluteUrl = new URL(source, document.baseURI).href;
  try {
    if (/\.docx$/i.test(source)) {
      const [buffer] = await Promise.all([readDocxBuffer(source, absoluteUrl), loadWordLibrary()]);
      docxViewer.replaceChildren();
      await window.docx.renderAsync(buffer, docxViewer, null, { inWrapper: true, ignoreWidth: true, ignoreHeight: true, breakPages: false });
    } else {
      const { protocol, hostname } = new URL(absoluteUrl);
      if (!/^https?:$/.test(protocol) || ["localhost", "127.0.0.1"].includes(hostname)) {
        showWordMessage(translate("document.docOffline"));
        return;
      }
      docxViewer.hidden = true;
      documentViewer.hidden = false;
      documentViewer.title = title;
      documentViewer.src = `https://view.officeapps.live.com/op/embed.aspx?src=${encodeURIComponent(absoluteUrl)}`;
    }
  } catch (error) {
    console.error("Could not open the Word document:", error);
    docxViewer.hidden = false;
    showWordMessage(translate("document.error"));
  }
}
