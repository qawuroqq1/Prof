function loadScript(src) {
  return new Promise((resolve, reject) => {
    const script = document.createElement("script");
    script.src = src;
    script.onload = resolve;
    script.onerror = () => reject(new Error(`Could not load ${src}`));
    document.head.append(script);
  });
}

function loadWordLibrary() {
  if (!wordLibraryPromise) {
    wordLibraryPromise = wordScripts.reduce((chain, src) => chain.then(() => loadScript(src)), Promise.resolve())
      .catch((error) => { wordLibraryPromise = null; throw error; });
  }
  return wordLibraryPromise;
}

