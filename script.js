async function askAssistant(question) {
  if (!assistantInput || !question.trim()) return;
  const prompt = question.trim();
  const form = document.getElementById("assistant-form");
  const submitButton = form?.querySelector('button[type="submit"]');
  addAssistantMessage(prompt, "assistant-question");
  if (form instanceof HTMLFormElement) form.reset();

  if (!ASSISTANT_API_URL) {
    addAssistantMessage(getAssistantAnswer(prompt), "assistant-reply");
    assistantInput.focus();
    return;
  }

  if (submitButton instanceof HTMLButtonElement) submitButton.disabled = true;
  assistantOptions?.setAttribute("aria-busy", "true");
  assistantOptions?.querySelectorAll("button").forEach((button) => { button.disabled = true; });
  addAssistantMessage(translate("assistant.loading"), "assistant-reply");
  const loadingMessage = assistantMessages?.lastElementChild;
  try {
    const response = await fetch(ASSISTANT_API_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        question: prompt,
        language: currentLanguage,
        messages: assistantConversation.slice(-8)
      })
    });
    if (!response.ok) throw new Error(`Assistant request failed (${response.status})`);
    const result = await response.json();
    if (typeof result.answer !== "string" || !result.answer.trim()) {
      throw new Error("Assistant returned an empty answer");
    }
    if (loadingMessage) loadingMessage.textContent = result.answer;
    assistantConversation.push({ role: "user", content: prompt }, { role: "assistant", content: result.answer });
    assistantOptions?.scrollIntoView({ block: "nearest" });
  } catch (error) {
    console.error("Could not get an assistant response:", error);
    if (loadingMessage) loadingMessage.textContent = translate("assistant.error");
  } finally {
    if (submitButton instanceof HTMLButtonElement) submitButton.disabled = false;
    assistantOptions?.removeAttribute("aria-busy");
    assistantOptions?.querySelectorAll("button").forEach((button) => { button.disabled = false; });
    assistantInput.focus();
  }
}

function getAssistantAnswer(question) {
  const text = question.toLocaleLowerCase();
  if (/контакт|телефон|адрес|почт|байланыс|телефон|мекенжай|пошта|contact|phone|address|email/.test(text)) {
    return translate("assistant.contactAnswer");
  }
  const topics = [
    { pattern: /коллектив|ұжымдық|collective/, answer: "faq.a3" },
    { pattern: /курс|обуч|оқу|оқыт|курс|training|course|learn/, answer: "faq.a4" },
    { pattern: /кодекс|закон|заң|нпа|әділет|адилет|law|code|regulation/, answer: "faq.a5" },
    { pattern: /консульт|юрист|правов|кеңес|заңгер|consult|legal|lawyer/, answer: "faq.a2" },
    { pattern: /зарплат|увольн|труд|еңбек|жұмыс|жалақ|құқық|құқы|labou?r|salary|dismiss|rights/, answer: "faq.a1" }
  ];
  const topic = topics.find((item) => item.pattern.test(text));
  return topic ? translate(topic.answer) : translate("assistant.fallback");
}

