function getAssistantAnswer(question) {
  const text = question.toLocaleLowerCase();
  if (/контакт|телефон|адрес|почт|байланыс|телефон|мекенжай|пошта|contact|phone|address|email/.test(text)) {
    return translate("assistant.contactAnswer");
  }
  const topics = [
    { pattern: /коллектив|ұжымдық|collective/, answer: "faq.a3" },
    { pattern: /курс|обуч|оқу|оқыт|курс|training|course|learn/, answer: "faq.a4" },
    { pattern: /кодекс|закон|заң|нпа|әділет|адилет|law|code|regulation/, answer: "faq.a5" },
    { pattern: /консульт|юрист|правов|кеңес|заңгер|consult|legal|lawyer/, answer: "faq.a2" },
    { pattern: /зарплат|увольн|труд|еңбек|жұмыс|жалақ|құқық|құқы|labou?r|salary|dismiss|rights/, answer: "faq.a1" }
  ];
  const topic = topics.find((item) => item.pattern.test(text));
  return topic ? translate(topic.answer) : translate("assistant.fallback");
}

