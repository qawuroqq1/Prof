async function loadLeadershipMembers(section, language) {
  const sourceLanguage = language === "kz" ? "kaz" : "rus";
  const source = `${downloadsPath}/about/015-${sourceLanguage}.docx`;
  const absoluteUrl = new URL(source, document.baseURI).href;
  const [buffer] = await Promise.all([readDocxBuffer(source, absoluteUrl), loadWordLibrary()]);
  if (!window.JSZip) throw new Error("The Word document parser is unavailable");

  const zip = await window.JSZip.loadAsync(buffer);
  const documentXml = await zip.file("word/document.xml")?.async("text");
  if (!documentXml) throw new Error("The leadership document has no content");
  const xml = new DOMParser().parseFromString(documentXml, "application/xml");
  if (xml.getElementsByTagName("parsererror").length) throw new Error("The leadership document is invalid");

  const wordNamespace = "http://schemas.openxmlformats.org/wordprocessingml/2006/main";
  const tables = Array.from(xml.getElementsByTagNameNS(wordNamespace, "tbl"));
  const tableIndex = section === "council" ? 0 : 1;
  const table = tables[tableIndex];
  if (!table) throw new Error(`The ${section} roster was not found`);

  const rows = Array.from(table.getElementsByTagNameNS(wordNamespace, "tr"));
  const members = rows.map((row) => {
    const cells = Array.from(row.childNodes).filter((node) =>
      node.nodeType === 1 && node.namespaceURI === wordNamespace && node.localName === "tc"
    );
    return cells.map((cell) =>
      Array.from(cell.getElementsByTagNameNS(wordNamespace, "t")).map((text) => text.textContent || "").join("").trim()
    );
  }).filter((cells) => /^\d+$/.test(cells[0] || "") && cells[1] && cells[2])
    .map((cells) => ({
      name: normalizeLeadershipText(cells[1]),
      role: localizeLeadershipRole(cells[2], language)
    }));

  if (!members.length) throw new Error(`The ${section} roster is empty`);
  return members;
}

